-- 01_schema.sql — Execute against the NEXUSMART WAREHOUSE database, not Airflow metadata.
-- Staging mirrors the actual CLEANED CSV headers; TEXT columns preserve raw cleaned values.
-- Only the warehouse dimension/fact tables use typed fields.
CREATE SCHEMA IF NOT EXISTS public;
SET search_path TO public;

CREATE TABLE IF NOT EXISTS stg_locations (
    "city_id" TEXT,
    "city" TEXT,
    "province" TEXT,
    "region" TEXT,
    "latitude" TEXT,
    "longitude" TEXT,
    "population_tier" TEXT
);

CREATE TABLE IF NOT EXISTS stg_sellers (
    "seller_id" TEXT,
    "seller_name" TEXT,
    "join_date" TEXT,
    "seller_tier" TEXT,
    "city_id" TEXT,
    "rating" TEXT
);

CREATE TABLE IF NOT EXISTS stg_products (
    "product_id" TEXT,
    "product_name" TEXT,
    "category" TEXT,
    "sub_category" TEXT,
    "brand" TEXT,
    "list_price" TEXT,
    "cost_price" TEXT,
    "weight_kg" TEXT,
    "seller_id" TEXT
);

CREATE TABLE IF NOT EXISTS stg_customers (
    "customer_id" TEXT,
    "full_name" TEXT,
    "email" TEXT,
    "phone" TEXT,
    "gender" TEXT,
    "registration_date" TEXT,
    "city_id" TEXT,
    "birth_year" TEXT
);

CREATE TABLE IF NOT EXISTS stg_orders (
    "order_id" TEXT,
    "customer_id" TEXT,
    "order_date" TEXT,
    "order_status" TEXT,
    "ship_city_id" TEXT,
    "order_total" TEXT,
    "discount_code" TEXT,
    "channel" TEXT,
    "order_date_raw" TEXT,
    "order_date_issue" TEXT,
    "discount_pct" TEXT,
    "customer_orphan" TEXT
);

CREATE TABLE IF NOT EXISTS stg_order_items (
    "order_item_id" TEXT,
    "order_id" TEXT,
    "product_id" TEXT,
    "seller_id" TEXT,
    "quantity" TEXT,
    "unit_price" TEXT,
    "discount_amount" TEXT,
    "product_orphan" TEXT
);

CREATE TABLE IF NOT EXISTS stg_payments (
    "payment_id" TEXT,
    "order_id" TEXT,
    "payment_method" TEXT,
    "payment_status" TEXT,
    "amount" TEXT,
    "payment_date" TEXT,
    "payment_rank" TEXT
);

CREATE TABLE IF NOT EXISTS stg_shipping (
    "shipment_id" TEXT,
    "order_id" TEXT,
    "courier" TEXT,
    "shipped_date" TEXT,
    "delivered_date" TEXT,
    "shipping_fee" TEXT,
    "delivery_status" TEXT,
    "shipping_fee_missing" TEXT
);

CREATE TABLE IF NOT EXISTS stg_returns (
    "return_id" TEXT,
    "order_item_id" TEXT,
    "return_date" TEXT,
    "return_reason" TEXT,
    "return_status" TEXT,
    "refund_amount" TEXT,
    "is_valid_return" TEXT
);

CREATE TABLE IF NOT EXISTS rejects (
  source_file TEXT, record_id TEXT, reason_code TEXT, detail TEXT, raw_record TEXT
);
CREATE TABLE IF NOT EXISTS customer_map (old_id TEXT, master_id TEXT);
CREATE TABLE IF NOT EXISTS product_map (old_id TEXT, master_id TEXT);
CREATE TABLE IF NOT EXISTS pipeline_run_log (
  log_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  run_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  step TEXT NOT NULL, rows_affected BIGINT, notes TEXT
);

CREATE TABLE IF NOT EXISTS "DimDate" (
  "DateKey" INTEGER PRIMARY KEY,
  "FullDate" DATE UNIQUE,
  "Day" INTEGER, "Week" INTEGER, "Month" INTEGER,
  "Quarter" INTEGER, "Year" INTEGER, "DayName" TEXT,
  "IsWeekend" BOOLEAN, "IsHoliday" BOOLEAN,
  "IsRamadan" BOOLEAN, "IsEidUlFitr" BOOLEAN, "IsEidUlAdha" BOOLEAN,
  "Is14August" BOOLEAN, "Is1111" BOOLEAN, "IsBlackFriday" BOOLEAN
);
CREATE TABLE IF NOT EXISTS "DimCustomer" (
  "CustomerKey" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CustomerID" TEXT UNIQUE,
  "FullName" TEXT, "Email" TEXT, "Phone" TEXT,
  "Gender" TEXT, "BirthYear" INTEGER, "RegistrationDate" DATE,
  "CityID" TEXT, "City" TEXT, "Province" TEXT, "Region" TEXT
);
CREATE TABLE IF NOT EXISTS "DimProduct" (
  "ProductKey" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ProductID" TEXT UNIQUE, "ProductName" TEXT,
  "Category" TEXT, "SubCategory" TEXT, "Brand" TEXT,
  "ListPrice" NUMERIC(16,2), "CostPrice" NUMERIC(16,2),
  "WeightKg" NUMERIC(14,4)
);
CREATE TABLE IF NOT EXISTS "DimSeller" (
  "SellerKey" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "SellerID" TEXT UNIQUE, "SellerName" TEXT, "JoinDate" DATE,
  "SellerTier" TEXT, "Rating" NUMERIC(6,2),
  "CityID" TEXT, "City" TEXT, "Province" TEXT, "Region" TEXT
);
CREATE TABLE IF NOT EXISTS "DimLocation" (
  "LocationKey" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CityID" TEXT UNIQUE, "City" TEXT, "Province" TEXT,
  "Region" TEXT, "PopulationTier" TEXT,
  "Latitude" NUMERIC(12,7), "Longitude" NUMERIC(12,7)
);
CREATE TABLE IF NOT EXISTS "FactSales" (
  "OrderItemID" TEXT PRIMARY KEY,
  "OrderID" TEXT NOT NULL,
  "DateKey" INTEGER NOT NULL REFERENCES "DimDate"("DateKey"),
  "ReturnDateKey" INTEGER REFERENCES "DimDate"("DateKey"),
  "CustomerKey" INTEGER NOT NULL REFERENCES "DimCustomer"("CustomerKey"),
  "ProductKey" INTEGER NOT NULL REFERENCES "DimProduct"("ProductKey"),
  "SellerKey" INTEGER NOT NULL REFERENCES "DimSeller"("SellerKey"),
  "LocationKey" INTEGER NOT NULL REFERENCES "DimLocation"("LocationKey"),
  "Quantity" NUMERIC(16,3), "UnitPrice" NUMERIC(16,2),
  "GrossAmount" NUMERIC(18,2), "DiscountAmount" NUMERIC(18,2),
  "NetAmount" NUMERIC(18,2), "CostAmount" NUMERIC(18,2),
  "ShippingFee" NUMERIC(18,2), "ShippingDays" INTEGER,
  "IsCancelled" BOOLEAN NOT NULL, "IsReturned" BOOLEAN NOT NULL,
  "ReturnedAmount" NUMERIC(18,2), "ReturnReason" TEXT,
  "ReturnStatus" TEXT, "OrderStatus" TEXT,
  "PaymentMethod" TEXT, "Channel" TEXT
);
CREATE INDEX IF NOT EXISTS idx_fact_date ON "FactSales"("DateKey");
CREATE INDEX IF NOT EXISTS idx_fact_customer ON "FactSales"("CustomerKey");
CREATE INDEX IF NOT EXISTS idx_fact_product ON "FactSales"("ProductKey");
CREATE INDEX IF NOT EXISTS idx_fact_seller ON "FactSales"("SellerKey");
CREATE INDEX IF NOT EXISTS idx_fact_location ON "FactSales"("LocationKey");
CREATE INDEX IF NOT EXISTS idx_fact_order ON "FactSales"("OrderID");
